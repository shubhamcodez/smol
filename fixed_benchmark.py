"""Fixed pretrain evaluator for the autoresearch loop.

Do not edit this file during a search run. It owns the wall-clock budget,
held-out BPB metric, truncated MMLU/ARC/OpenBookQA gate, and overall score.
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path
from typing import Any

import torch

from backend import detect_runtime
from model import ModelConfig, TransformerLM
from pretrain_eval import (
    BENCH_WEIGHT,
    evaluate_bpb,
    evaluate_mcq_accuracy,
    load_benchmark_items,
    overall_score,
)
from token_dataset import TokenShard, default_shard_paths


ROOT = Path(__file__).resolve().parent
ALLOWED_N_LAYER = {2, 4, 6, 8, 12}
ALLOWED_N_EMBD = {128, 256, 384, 512, 768}
ALLOWED_BATCH = {1, 2, 4, 8}
ALLOWED_SEQ = {128, 256, 512, 1024}


def validate_candidate(candidate: dict[str, Any]) -> None:
    required = {
        "n_layer",
        "n_embd",
        "n_head",
        "n_kv_head",
        "intermediate_size",
        "max_seq_len",
        "learning_rate",
        "weight_decay",
        "batch_size",
        "beta1",
        "beta2",
        "seed",
    }
    missing = required - candidate.keys()
    if missing:
        raise ValueError(f"candidate is missing keys: {sorted(missing)}")
    if int(candidate["n_layer"]) not in ALLOWED_N_LAYER:
        raise ValueError("n_layer is outside the fixed search space")
    if int(candidate["n_embd"]) not in ALLOWED_N_EMBD:
        raise ValueError("n_embd is outside the fixed search space")
    if int(candidate["batch_size"]) not in ALLOWED_BATCH:
        raise ValueError("batch_size is outside the fixed search space")
    if int(candidate["max_seq_len"]) not in ALLOWED_SEQ:
        raise ValueError("max_seq_len is outside the fixed search space")
    if not 1e-5 <= float(candidate["learning_rate"]) <= 3e-3:
        raise ValueError("learning_rate is outside the fixed search space")
    if not 0.0 <= float(candidate["weight_decay"]) <= 0.2:
        raise ValueError("weight_decay is outside the fixed search space")
    if not 0.0 < float(candidate["beta1"]) < 1.0 or not 0.0 < float(candidate["beta2"]) < 1.0:
        raise ValueError("Adam betas must be between zero and one")
    if int(candidate["n_embd"]) % int(candidate["n_head"]) != 0:
        raise ValueError("n_embd must be divisible by n_head")
    if int(candidate["n_head"]) % int(candidate["n_kv_head"]) != 0:
        raise ValueError("n_head must be divisible by n_kv_head")


def build_config(candidate: dict[str, Any]) -> ModelConfig:
    return ModelConfig(
        vocab_size=50_304,
        max_seq_len=int(candidate["max_seq_len"]),
        n_layer=int(candidate["n_layer"]),
        n_embd=int(candidate["n_embd"]),
        n_head=int(candidate["n_head"]),
        n_kv_head=int(candidate["n_kv_head"]),
        intermediate_size=int(candidate["intermediate_size"]),
    )


def choose_training_backend(requested: str) -> str:
    inventory = detect_runtime()
    training = requested
    if training == "auto":
        training = "cuda" if inventory.cuda else "cpu"
    if training == "cuda" and not inventory.cuda:
        raise RuntimeError("CUDA training was required but torch.cuda.is_available() is false")
    return training


def train_for_budget(
    candidate: dict[str, Any],
    train_shard: TokenShard,
    budget_seconds: float,
    device: torch.device,
) -> tuple[TransformerLM, int, float]:
    torch.manual_seed(int(candidate["seed"]))
    if device.type == "cuda":
        torch.cuda.manual_seed_all(int(candidate["seed"]))

    config = build_config(candidate)
    model = TransformerLM(config).to(device)
    model.gradient_checkpointing_enable()
    optimizer = model.configure_optimizer(
        weight_decay=float(candidate["weight_decay"]),
        learning_rate=float(candidate["learning_rate"]),
        betas=(float(candidate["beta1"]), float(candidate["beta2"])),
        device_type=device.type,
    )
    scaler = torch.amp.GradScaler("cuda", enabled=device.type == "cuda")
    generator = torch.Generator(device="cpu").manual_seed(int(candidate["seed"]) + 1)
    batch_size = int(candidate["batch_size"])
    seq_len = int(candidate["max_seq_len"])

    if device.type == "cuda":
        torch.cuda.synchronize()
    start = time.perf_counter()
    step = 0
    while step < 5 or time.perf_counter() - start < budget_seconds:
        step += 1
        inputs, targets = train_shard.sample_batch(batch_size, seq_len, generator, device)
        optimizer.zero_grad(set_to_none=True)
        with torch.autocast(device_type=device.type, dtype=torch.float16, enabled=device.type == "cuda"):
            result = model(
                inputs,
                targets=targets,
                return_logits=False,
                loss_chunk_size=min(128, seq_len),
            )
        if result.loss is None:
            raise RuntimeError("training step did not return a loss")
        scaler.scale(result.loss).backward()
        scaler.step(optimizer)
        scaler.update()
        if device.type == "cuda" and step % 5 == 0:
            torch.cuda.synchronize()
    if device.type == "cuda":
        torch.cuda.synchronize()
    return model, step, time.perf_counter() - start


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--candidate", type=Path, required=True)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--artifacts", type=Path, required=True)
    parser.add_argument("--budget-seconds", type=float, default=30.0)
    parser.add_argument("--training-backend", choices=["auto", "cpu", "cuda"], default="auto")
    parser.add_argument("--benchmark-limit", type=int, default=32)
    parser.add_argument("--bpb-batches", type=int, default=8)
    args = parser.parse_args()

    candidate = json.loads(args.candidate.read_text(encoding="utf-8"))
    validate_candidate(candidate)
    training_backend = choose_training_backend(args.training_backend)
    device = torch.device("cuda" if training_backend == "cuda" else "cpu")

    shards = default_shard_paths(ROOT)
    train_shard = TokenShard(shards.train)
    val_shard = TokenShard(shards.val)

    model, steps, train_seconds = train_for_budget(
        candidate, train_shard, args.budget_seconds, device
    )

    seq_len = int(candidate["max_seq_len"])
    bpb_metrics = evaluate_bpb(
        model,
        val_shard,
        seq_len=seq_len,
        batch_size=min(2, int(candidate["batch_size"])),
        max_batches=args.bpb_batches,
        seed=int(candidate["seed"]) + 7,
        device=device,
    )
    items = load_benchmark_items(args.benchmark_limit)
    bench = evaluate_mcq_accuracy(model, items, device)
    parameter_count = model.get_num_params()
    score = overall_score(
        bpb_metrics["bpb"],
        bench["mean_benchmark_acc"],
        parameter_count,
    )

    run_dir = args.artifacts / args.run_id
    run_dir.mkdir(parents=True, exist_ok=True)
    metrics = {
        "run_id": args.run_id,
        "score": score,
        "bpb": bpb_metrics["bpb"],
        "validation_loss": bpb_metrics["validation_loss"],
        "mean_benchmark_acc": bench["mean_benchmark_acc"],
        "task_accuracy": bench["task_accuracy"],
        "benchmark_examples": bench["examples_evaluated"],
        "benchmark_weight": BENCH_WEIGHT,
        "parameter_count": parameter_count,
        "training_backend": training_backend,
        "training_seconds": train_seconds,
        "training_steps": steps,
        "candidate": candidate,
        "runtime_inventory": detect_runtime().to_dict(),
        "score_formula": "bpb + 2.0 * (1 - mean_benchmark_acc) + 1e-9 * params",
    }
    (run_dir / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    print("AUTORESEARCH_METRICS " + json.dumps(metrics, separators=(",", ":")))


if __name__ == "__main__":
    main()
